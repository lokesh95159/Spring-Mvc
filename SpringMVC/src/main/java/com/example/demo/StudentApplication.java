package com.example.demo;

import org.springframework.boot.SpringApplication;
import org.springframework.boot.autoconfigure.SpringBootApplication;
import org.springframework.stereotype.Controller;
import org.springframework.ui.Model;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.ResponseBody;
import org.springframework.jdbc.core.JdbcTemplate;
import jakarta.annotation.PostConstruct;
import java.util.List;

@SpringBootApplication
@Controller
public class StudentApplication {

    private final JdbcTemplate db;

    public StudentApplication(JdbcTemplate db) {
        this.db = db;
    }

    public static void main(String[] args) {
        SpringApplication.run(StudentApplication.class, args);
    }

    // JDBC: Create a database table when the application starts.
    @PostConstruct
    public void createTable() {
        db.execute("CREATE TABLE IF NOT EXISTS students (" +
                   "id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                   "name VARCHAR(100), email VARCHAR(150), age INT)");
    }

    // VIEW: A simple HTML form (embedded in the Java file).
    private static final String FORM = """
        <!DOCTYPE html>
        <html><head><title>Student Registration</title></head>
        <body style='font-family:Arial;max-width:600px;margin:50px auto'>
          <h2>Student Registration - Spring MVC</h2>
          <form action='/register' method='post'>
            Name: <input name='name' required><br><br>
            Email: <input type='email' name='email' required><br><br>
            Age: <input type='number' name='age' required><br><br>
            <button type='submit'>Register</button>
          </form>
          <p><a href='/students'>View Registered Students</a></p>
        </body></html>
        """;

    // REQUEST MAPPING: Display the HTML form.
    @GetMapping("/")
    @ResponseBody
    public String home() {
        return FORM;
    }

    // CONTROLLER + FORM HANDLING + VALIDATION + JDBC
    @PostMapping("/register")
    @ResponseBody
    public String register(@RequestParam String name,
                           @RequestParam String email,
                           @RequestParam int age) {
        if (name.isBlank() || !email.contains("@") || age < 18) {
            return "Invalid details! Name, email and age (18+) are required. " +
                   "<a href='/'>Try again</a>";
        }

        db.update("INSERT INTO students (name, email, age) VALUES (?, ?, ?)",
                  name, email, age);
        return "<h2>Registration Successful!</h2>" +
               "<a href='/students'>View Students</a>";
    }

    // MODEL: Represents one student record.
    public record Student(int id, String name, String email, int age) {}

    // JDBC + MODEL + VIEW: Retrieve and display registered students.
    @GetMapping("/students")
    @ResponseBody
    public String students(Model model) {
        List<Student> students = db.query(
            "SELECT id, name, email, age FROM students ORDER BY id",
            (rs, rowNum) -> new Student(
                rs.getInt("id"), rs.getString("name"),
                rs.getString("email"), rs.getInt("age")));
        model.addAttribute("students", students);

        StringBuilder html = new StringBuilder("""
            <html><body style='font-family:Arial'>
            <h2>Registered Students</h2>
            <table border='1' cellpadding='8'>
            <tr><th>ID</th><th>Name</th><th>Email</th><th>Age</th></tr>
            """);
        for (Student s : students) {
            html.append("<tr><td>").append(s.id()).append("</td><td>")
                .append(escapeHtml(s.name())).append("</td><td>")
                .append(escapeHtml(s.email())).append("</td><td>")
                .append(s.age()).append("</td></tr>");
        }
        return html.append("</table><p><a href='/'>Add Student</a></p></body></html>")
                   .toString();
    }

    private static String escapeHtml(String value) {
        return value.replace("&", "&amp;").replace("<", "&lt;")
                    .replace(">", "&gt;").replace("\"", "&quot;")
                    .replace("'", "&#39;");
    }
}
